public class Main {
    public static void main(String[] args) {

        // Menyimpan berat badan menggunakan tipe data float
        // Tipe data float harus ditambahkan huruf f di belakang angka
        float bb = 55.5f;

        // Menyimpan tinggi badan menggunakan tipe data double
        double tb = 160.25;

        // Menampilkan nilai menggunakan printf
        System.out.printf("%f %f", bb, tb);

    }
}