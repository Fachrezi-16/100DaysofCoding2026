public class EscapeSequence {
    public static void main(String[] args) {

        // \n digunakan untuk membuat baris baru
        System.out.println("Awali harimu\ndengan ngoding");

        // \t digunakan untuk memberikan jarak seperti Tab
        System.out.println("Rabu\t00.00-23.59\tDay1Ngoding");
        System.out.println("Kamis\t00.00-23.59\tDay2Ngoding");

        // \" digunakan untuk menampilkan tanda petik dua
        System.out.println("Gwejh Berkata \"When yah Jago Ngoding!\"");

        // \' digunakan untuk menampilkan tanda petik satu
        System.out.println("Hari ini adalah \'Hari ke-3\'");

        // \\ digunakan untuk menampilkan tanda backslash
        System.out.println("C:\\Java\\Belajar");

    }
}
