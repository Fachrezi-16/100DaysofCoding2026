public class TipeDataNumerikBilanganBulat {
    public static void main(String[] args) {

        // byte digunakan untuk bilangan bulat kecil
        byte jumlahKelas = 10;

        // short digunakan untuk bilangan bulat
        short jumlahMahasiswa = 300;

        // int digunakan untuk bilangan bulat yang umum
        int jumlahKomputer = 5000;

        // long digunakan untuk bilangan bulat yang sangat besar
        long jumlahData = 1000000000L;

        System.out.println("Jumlah Kelas       : " + jumlahKelas);
        System.out.println("Jumlah Mahasiswa   : " + jumlahMahasiswa);
        System.out.println("Jumlah Komputer    : " + jumlahKomputer);
        System.out.println("Jumlah Data        : " + jumlahData);
    }
}
